/* Banner engine.
   Home: every live admin banner + one generated banner per collection.
   Collection page: only that collection's admin banners + up to two generated ones.
   Rank: admin priority (1-5) beats event > promo > notice, then generated by discount and freshness. */
window.Banners={pick:function(prods,admin,ctx){
  var t=Date.now(),W={event:3,promo:2,announcement:1},K={event:"Event",promo:"Promo",announcement:"Notice"},out=[];
  var stock=prods.filter(function(p){return p.stock==null||p.stock===""||p.stock>0});
  admin.forEach(function(b){
    var live=(!b.from||t>=Date.parse(b.from))&&(!b.to||t<=Date.parse(b.to)+864e5);
    if(!live||(ctx&&b.scope!==ctx))return;
    out.push({kind:K[b.type]||"Notice",title:b.title,text:b.text,img:b.img,href:b.link||"#/",score:1000*(b.priority||1)+10*(W[b.type]||1)});
  });
  var off=function(p){return Math.round((1-p.price/p.old)*100)};
  function spots(col,n){
    var l=stock.filter(function(p){return p.col===col});if(!l.length)return[];
    var r=[],d=l.filter(function(p){return p.old>p.price}).sort(function(a,b){return off(b)-off(a)})[0],
        f=l.slice().sort(function(a,b){return(b.at||0)-(a.at||0)})[0];
    if(d)r.push({kind:"Deal",title:col,text:off(d)+"% off "+d.name,img:d.img,href:"#/p/"+d.id,score:100+off(d)});
    if(!d||f.id!==d.id)r.push({kind:"New in",title:col,text:f.name,img:f.img,href:"#/p/"+f.id,score:60+(t-(f.at||0)<6048e5?20:0)});
    return r.slice(0,n);
  }
  var cs=[];stock.forEach(function(p){if(cs.indexOf(p.col)<0)cs.push(p.col)});
  if(ctx)out=out.concat(spots(ctx,2));else cs.forEach(function(c){out=out.concat(spots(c,1))});
  return out.sort(function(a,b){return b.score-a.score}).slice(0,8);
}};
