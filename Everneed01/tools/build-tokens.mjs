// Generates css/tokens.css: 6 palettes x 3 modes, every value an explicit hex or rgba (no runtime colour maths).
// Run: node tools/build-tokens.mjs   (then node tools/check-contrast.mjs)
import { writeFileSync } from 'node:fs';
import { hsl, hueOf, mix, over, shiftL, contrast } from './colors.mjs';

// Nudge a colour (darker on light modes, lighter on dark) until it reads at `min`:1 on every surface given.
function reach(hex, dark, min, surfaces) {
  let c = hex;
  for (let i = 0; i < 60 && surfaces.some((b) => contrast(c, b) < min); i++) c = shiftL(c, dark ? 1 : -1);
  return c;
}

export const PALETTES = {
  emerald: { name: 'Emerald', light: '#0F6B4F', dark: '#3FD39A' },
  indigo: { name: 'Indigo', light: '#4F46E5', dark: '#8E8CFF' },
  rose: { name: 'Rose', light: '#E11D48', dark: '#FF6B88' },
  violet: { name: 'Violet', light: '#7C3AED', dark: '#B18CFF' },
  ocean: { name: 'Ocean', light: '#0E7490', dark: '#34D3EE' },
  gold: { name: 'Gold', light: '#A16207', dark: '#F2C14E' },
};
const STATUS = {
  light: { success: '#15803D', warning: '#B45309', danger: '#B91C1C', info: '#1D4ED8', accent: '#B45309', star: '#D97706' },
  dark: { success: '#4ADE80', warning: '#FBBF24', danger: '#FF7A7A', info: '#7CB0FF', accent: '#F5A524', star: '#F5A524' },
};
const INK = '#04140E', WHITE = '#FFFFFF';

function theme(key, mode) {
  const p = PALETTES[key], h = hueOf(p.light), dark = mode !== 'light';
  const brand = dark ? p.dark : p.light;
  const n = mode === 'light'
    ? { bg: hsl(h, 20, 95.5), s1: WHITE, s2: hsl(h, 20, 98.2), s3: hsl(h, 18, 92.5), t1: hsl(h, 30, 8), t2: hsl(h, 15, 27), t3: hsl(h, 10, 36) }
    : mode === 'dark'
      ? { bg: hsl(h, 28, 5.5), s1: hsl(h, 24, 9), s2: hsl(h, 22, 12.5), s3: hsl(h, 20, 16.5), t1: hsl(h, 18, 93), t2: hsl(h, 14, 78), t3: hsl(h, 10, 63) }
      : { bg: '#000000', s1: hsl(h, 22, 4.5), s2: hsl(h, 20, 8), s3: hsl(h, 18, 11.5), t1: hsl(h, 18, 93), t2: hsl(h, 14, 78), t3: hsl(h, 10, 63) };
  // Light borders are solid and darkened until they are visible (1.3:1) against the page background.
  let border = null;
  if (!dark) { border = hsl(h, 12, 86); for (let i = 0; i < 40 && contrast(border, n.bg) < 1.32; i++) border = shiftL(border, -1); }
  let alpha = 0.1;
  if (dark) while (alpha < 0.4 && [n.bg, n.s1].some((b) => contrast(over('#FFFFFF', alpha, b), b) < 1.33)) alpha = Math.round((alpha + 0.01) * 100) / 100;
  const raw = STATUS[dark ? 'dark' : 'light'], bgs = [n.bg, n.s1];
  const s = Object.fromEntries(Object.entries(raw).map(([k, v]) => [k, reach(v, dark, k === 'star' ? 3.1 : 5.3, bgs)]));
  const brandSoft = mix(brand, n.s1, dark ? 0.16 : 0.1);
  const brandInk = reach(brand, dark, 4.7, [n.bg, n.s1, n.s2, brandSoft]);
  const onBrand = contrast(INK, brand) > contrast(WHITE, brand) ? INK : WHITE;
  const t = {
    bg: n.bg, 'surface-1': n.s1, 'surface-2': n.s2, 'surface-3': n.s3,
    border: dark ? `rgba(255,255,255,${alpha})` : border, 'border-strong': dark ? `rgba(255,255,255,${Math.min(alpha + 0.08, 0.5)})` : shiftL(border, -8),
    'text-1': n.t1, 'text-2': n.t2, 'text-3': n.t3,
    brand, 'brand-ink': brandInk, 'brand-hover': shiftL(brand, dark ? 7 : -7), 'brand-soft': brandSoft, 'text-on-brand': onBrand,
    accent: s.accent, star: s.star, success: s.success, warning: s.warning, danger: s.danger, info: s.info,
    'danger-soft': mix(s.danger, n.s1, dark ? 0.16 : 0.09), 'success-soft': mix(s.success, n.s1, dark ? 0.16 : 0.1), 'warning-soft': mix(s.warning, n.s1, dark ? 0.16 : 0.12),
    glass: `${hexA(n.bg, 0.82)}`, scrim: 'rgba(0,0,0,.55)', 'on-image': '#FFFFFF', 'image-scrim': 'rgba(0,0,0,.62)',
    'shadow-1': dark ? '0 1px 0 rgba(255,255,255,.06) inset, 0 1px 2px rgba(0,0,0,.5)' : '0 1px 2px rgba(15,30,25,.08), 0 1px 1px rgba(15,30,25,.04)',
    'shadow-2': dark ? '0 1px 0 rgba(255,255,255,.07) inset, 0 10px 28px rgba(0,0,0,.55)' : '0 10px 28px rgba(15,30,25,.14), 0 2px 6px rgba(15,30,25,.06)',
    glow: dark ? `0 0 0 1px ${hexA(brand, 0.35)}, 0 6px 22px ${hexA(brand, 0.28)}` : `0 6px 18px ${hexA(brand, 0.28)}`,
    'color-scheme': dark ? 'dark' : 'light',
  };
  return t;
}
function hexA(hex, a) { const h = hex.replace('#', ''); const [r, g, b] = [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)); return `rgba(${r},${g},${b},${a})`; }
const block = (sel, t) => `${sel}{${Object.entries(t).map(([k, v]) => (k === 'color-scheme' ? `color-scheme:${v}` : `--${k}:${v}`)).join(';')}}\n`;

let css = '/* GENERATED by tools/build-tokens.mjs. Do not edit by hand. 6 palettes x 3 modes. */\n';
css += '/* Static tokens */\n:root{--r-chip:10px;--r-input:14px;--r-card:20px;--r-sheet:28px;--r-pill:999px;--sp-1:4px;--sp-2:8px;--sp-3:12px;--sp-4:16px;--sp-5:24px;--sp-6:32px;--t-fast:120ms;--t-base:220ms;--t-slow:360ms;--ease:cubic-bezier(.2,.7,.2,1);--font-display:"Bricolage Grotesque",system-ui,sans-serif;--media-bg:#000;--on-banner-dark:#111111;--scrim-soft:rgba(0,0,0,.22);--on-image-soft:rgba(255,255,255,.18);--on-image-line:rgba(255,255,255,.35);--font-body:"Figtree",system-ui,-apple-system,"Segoe UI",Roboto,sans-serif}\n';
css += block(':root', theme('emerald', 'light'));                       // default before the theme script runs
css += `@media(prefers-color-scheme:dark){\n${block(':root:not([data-mode])', theme('emerald', 'dark'))}}\n`;
for (const key of Object.keys(PALETTES)) for (const mode of ['light', 'dark', 'amoled']) css += block(`[data-palette=${key}][data-mode=${mode}]`, theme(key, mode));
// Emerald is the default palette, so html without data-palette follows data-mode only.
for (const mode of ['light', 'dark', 'amoled']) css += block(`[data-mode=${mode}]:not([data-palette])`, theme('emerald', mode));
writeFileSync(new URL('../css/tokens.css', import.meta.url), css);
console.log('css/tokens.css written,', css.length, 'bytes');
